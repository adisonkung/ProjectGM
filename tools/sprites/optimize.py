#!/usr/bin/env python3
"""
Sprite optimizer: public/sprites/*.png (the pipeline's canonical output, kept as-is) → public/sprites/opt/ for the game.

  * WebP: lossy q90 (alpha kept exact enough for soft FX), lossless for `pixelated` sheets; a file whose WebP is not
    at least 8 % smaller stays PNG (re-saved optimised).
  * FX strips wider than LIMIT px (one row of 20–30 frames, up to 11k px — over many GPUs' texture limit and slow to
    decode) are re-packed into a grid of whole frames (cols × rows) no wider than LIMIT. Renderers read the grid from
    the generated atlas (DOM + Pixi). Character sheets keep their grid (rows = clips) — already ≤ 5.5k wide, the
    Pixi layer chunks those when a GPU is smaller.
  * Writes src/app/core/data/sprite-atlas.ts (file → url + grid) — generated, do not edit.
  * Skips files whose output is newer than the source (re-run after any tools/sprites/* bake).

Run:  npm run sprites:optimize        (dumps the FX / sheet data first: tools/dev/sprite-dump.ts)
      python3 tools/sprites/optimize.py dist/sprite-dump.json [--force]
"""
import io
import json
import math
import os
import sys
from multiprocessing import Pool

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SRC = os.path.join(ROOT, 'public', 'sprites')
OUT = os.path.join(SRC, 'opt')
ATLAS = os.path.join(ROOT, 'src', 'app', 'core', 'data', 'sprite-atlas.ts')
LIMIT = 4096
QUALITY = 90
MIN_GAIN = 0.92


def plan(file, info):
    """layout for one file: grid for long FX strips, None = unchanged"""
    if info.get('kind') != 'fx':
        return None
    with Image.open(os.path.join(SRC, file)) as im:
        w, h = im.size
    strip = info['strip']
    if w <= LIMIT or strip <= 1:
        return None
    fw = w // strip
    cols = max(1, LIMIT // fw)
    return {'cols': cols, 'rows': math.ceil(strip / cols), 'fw': fw, 'fh': h, 'strip': strip}


def repack(im, lay):
    out = Image.new('RGBA', (lay['cols'] * lay['fw'], lay['rows'] * lay['fh']), (0, 0, 0, 0))
    for i in range(lay['strip']):
        frame = im.crop((i * lay['fw'], 0, (i + 1) * lay['fw'], lay['fh']))
        out.paste(frame, ((i % lay['cols']) * lay['fw'], (i // lay['cols']) * lay['fh']))
    return out


def encode(job):
    file, info, force = job
    src = os.path.join(SRC, file)
    stem = os.path.splitext(file)[0]
    lay = plan(file, info)
    prev = [p for p in (os.path.join(OUT, stem + '.webp'), os.path.join(OUT, stem + '.png')) if os.path.exists(p)]
    meta_path = os.path.join(OUT, stem + '.json')
    if not force and prev and os.path.getmtime(prev[0]) >= os.path.getmtime(src) and os.path.exists(meta_path):
        with open(meta_path) as f:
            meta = json.load(f)
        if meta.get('layout') == lay:
            return meta
    im = Image.open(src).convert('RGBA')
    if lay:
        im = repack(im, lay)
    lossless = bool(info.get('pixelated'))
    buf = io.BytesIO()
    if lossless:
        im.save(buf, 'WEBP', lossless=True, method=4)
    else:
        im.save(buf, 'WEBP', quality=QUALITY, alpha_quality=100, method=4)
    png = io.BytesIO()
    im.save(png, 'PNG', optimize=True)
    src_size = os.path.getsize(src)
    best_png = min(png.tell(), src_size) if not lay else png.tell()
    use_webp = buf.tell() < best_png * MIN_GAIN
    for p in prev:
        os.remove(p)
    if use_webp:
        name, data = stem + '.webp', buf.getvalue()
    elif lay or png.tell() < src_size:
        name, data = stem + '.png', png.getvalue()
    else:
        name, data = stem + '.png', open(src, 'rb').read()
    with open(os.path.join(OUT, name), 'wb') as f:
        f.write(data)
    meta = {'file': file, 'url': 'opt/' + name, 'layout': lay, 'before': src_size, 'after': len(data)}
    with open(meta_path, 'w') as f:
        json.dump(meta, f)
    return meta


def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    force = '--force' in sys.argv
    with open(args[0] if args else os.path.join(ROOT, 'dist', 'sprite-dump.json')) as f:
        dump = json.load(f)
    os.makedirs(OUT, exist_ok=True)
    jobs = [(file, info, force) for file, info in sorted(dump.items()) if os.path.exists(os.path.join(SRC, file))]
    with Pool(max(1, (os.cpu_count() or 2))) as pool:
        metas = pool.map(encode, jobs)
    # drop outputs of files that no longer exist / are no longer referenced
    keep = {os.path.splitext(m['url'][4:])[0] for m in metas}
    for f in os.listdir(OUT):
        if os.path.splitext(f)[0] not in keep:
            os.remove(os.path.join(OUT, f))
    lines = [
        '// GENERATED by tools/sprites/optimize.py (npm run sprites:optimize) — do not edit.',
        '// Game URL of each sprite file (public/sprites/<url>) and, for re-packed FX strips, the frame grid.',
        'export interface SpriteFile {',
        '  url: string;',
        '  /** FX strip re-packed into a grid: frame i at column i % cols, row ⌊i / cols⌋ */',
        '  cols?: number;',
        '  rows?: number;',
        '}',
        '',
        'export const SPRITE_ATLAS: Record<string, SpriteFile> = {',
    ]
    for m in sorted(metas, key=lambda m: m['file']):
        grid = f", cols: {m['layout']['cols']}, rows: {m['layout']['rows']}" if m['layout'] else ''
        lines.append(f"  '{m['file']}': {{ url: '{m['url']}'{grid} }},")
    lines.append('};')
    with open(ATLAS, 'w') as f:
        f.write('\n'.join(lines) + '\n')
    before = sum(m['before'] for m in metas)
    after = sum(m['after'] for m in metas)
    print(f'{len(metas)} files · {before / 1048576:.1f} MB → {after / 1048576:.1f} MB ({(1 - after / before) * 100:.0f}% smaller)')
    regrid = [m for m in metas if m['layout']]
    print(f"re-packed into grids (≤ {LIMIT} px): {len(regrid)} · " + ', '.join(f"{m['file']} {m['layout']['cols']}×{m['layout']['rows']}" for m in regrid))
    for m in sorted(metas, key=lambda m: -m['before'])[:8]:
        print(f"  {m['file']:42} {m['before'] // 1024:6d} KB → {m['after'] // 1024:6d} KB  {m['url']}")


if __name__ == '__main__':
    main()
