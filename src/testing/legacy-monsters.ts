/**
 * TEST FIXTURE — the pre-Forest-Arc tower roster (removed from the tower 2026-11-05, spec
 * claude/eldervane-monster-spec-s1-10.md). The engine keeps every mechanic those monsters exercised (bleed, soul link,
 * sacrifice, seal phases, Break casts, dives, ranged-only debuffs …); these specs keep testing them through the old
 * data. Importing this module registers each legacy monster / cast skill — under its own id, or under `legacy_<id>`
 * when the Forest Arc reuses that id (alpha_wolf, mist_wraith, call_of_the_forest …) — and exposes the old tower
 * floors with their spawns rewritten to those ids.
 * Never imported by app code.
 */
import { BUFFS, MONSTER_SKILLS, MONSTERS } from '../app/core/data/monsters';
import { LEGACY_TOWER_MONSTERS, LEGACY_TOWER_SKILLS } from '../app/core/data/legacy-tower-monsters';
import { LEGACY_TOWER_STAGES } from '../app/core/data/legacy-tower-stages';
import { monsterSheet, SHEETS } from '../app/core/data/sprites';
import { PROJECTILES } from '../app/core/data/monsters';
import { MonsterDefinition, MonsterSkillDefinition } from '../app/core/models/monster';
import { StageDef } from '../app/core/models/stage';

/** ids the Forest Arc (or anything else live) already uses → the legacy copy gets a `legacy_` prefix */
const MONSTER_IDS = new Set(Object.keys(LEGACY_TOWER_MONSTERS).filter(id => MONSTERS[id] && !id.startsWith('legacy_')));
const SKILL_IDS = new Set(Object.keys(LEGACY_TOWER_SKILLS).filter(id => MONSTER_SKILLS[id] && !id.startsWith('legacy_')));

/** legacy monster id → its fixture id (unchanged unless the live roster uses the same id) */
export const L = (id: string): string => (MONSTER_IDS.has(id) ? `legacy_${id}` : id);
export const LS = (id: string): string => (SKILL_IDS.has(id) ? `legacy_${id}` : id);

function renameSkill(s: MonsterSkillDefinition): MonsterSkillDefinition {
  const out: MonsterSkillDefinition = JSON.parse(JSON.stringify(s));
  out.id = LS(s.id);
  if (out.followUp) out.followUp.skill = LS(out.followUp.skill);
  const t = out.target as { monsterId?: string };
  if (t.monsterId) t.monsterId = L(t.monsterId);
  for (const c of out.conditions as { monsterId?: string }[]) if (c.monsterId) c.monsterId = L(c.monsterId);
  for (const e of out.effects) if (e.type === 'SUMMON') e.monsters = e.monsters.map(m => ({ ...m, id: L(m.id) }));
  return out;
}

function renameMonster(m: MonsterDefinition): MonsterDefinition {
  const out: MonsterDefinition = { ...m, id: L(m.id), skills: m.skills.map(LS), ai: { ...m.ai } };
  if (m.ai.skillPriority) out.ai.skillPriority = m.ai.skillPriority.map(LS);
  if (m.phases) {
    out.phases = m.phases.map(p => ({
      ...p,
      summon: p.summon?.map(s => ({ ...s, id: L(s.id) })),
      enableSkills: p.enableSkills?.map(s => ({ ...s, id: LS(s.id) })),
      cooldownOverride: p.cooldownOverride && Object.fromEntries(Object.entries(p.cooldownOverride).map(([k, v]) => [LS(k), v])),
    }));
  }
  return out;
}

for (const s of Object.values(LEGACY_TOWER_SKILLS)) MONSTER_SKILLS[LS(s.id)] = renameSkill(s);
for (const m of Object.values(LEGACY_TOWER_MONSTERS)) MONSTERS[L(m.id)] = renameMonster(m);
/** sheets only this fixture registers (the game no longer ships them optimised) */
export const LEGACY_SHEETS = new Set<string>();
// legacy art sheets (goblin fighter / archer, wolf, alpha) are no longer generated by sprites.ts — register them here
for (const m of Object.values(LEGACY_TOWER_MONSTERS)) {
  const sheet = m.animation.sheet;
  if (!sheet || SHEETS[sheet]) continue;
  LEGACY_SHEETS.add(sheet);
  const proj = m.attack.projectileId ? PROJECTILES[m.attack.projectileId]?.fx : undefined;
  SHEETS[sheet] = monsterSheet(m.animation, m.attack.event, proj);
}
// the legacy Alpha Howl buff stays registered in BUFFS (alpha_howl_buff) — nothing to add
void BUFFS;

/** the pre-Forest-Arc tower floors 1–10, spawning the `legacy_` monsters */
export const LEGACY_TOWER: StageDef[] = LEGACY_TOWER_STAGES.map(st => ({
  ...st,
  enemies: st.enemies.map(e => ({ ...e, enemy: L(e.enemy) })),
  rounds: st.rounds?.map(w => w.map(e => ({ ...e, enemy: L(e.enemy) }))),
}));
